#!/usr/bin/env python3
"""Per-layer wire RC for OpenROAD from a Cadence captable + the tech LEF (the kit has no QRC / OpenRCX deck).

    captable_rc.py <tech.lef> <file.captable> <corner> <out_prefix>

Writes <out_prefix>.tcl (set_layer_rc -corner <corner> per routing and cut layer, units kOhm/um and pF/um,
i.e. the liberty units of tcbn65gplus) and <out_prefix>.txt (same numbers in Ohm/um, fF/um, Ohm per via cut,
read by def2spef.py).  Both stay in the build directory on the server.

Approximation (documented in pnr/README.md):
  * every wire is a minimum-width wire (LEF WIDTH) at minimum pitch (spacing = PITCH - WIDTH) on BOTH sides;
  * C = Ctot(width, spacing) of the captable BASIC_CAP_TABLE (a wire over substrate between two neighbours),
    linearly interpolated in spacing; no layers above / below, no coupling caps kept (all to ground);
  * R = Rho(width, spacing) / (Thickness * (TopWidth + BottomWidth) / 2) from the PROCESS_VARIATION section
    (no wire-edge enlargement, no temperature coefficient);
  * via R = captable VIA Resistance per cut (VIAn joins Mn and Mn+1).
"""
import re
import sys


def lef_layers(path):
    """Ordered list of (name, type, width, pitch) of the ROUTING and CUT layers."""
    out, cur = [], None
    with open(path) as f:
        for line in f:
            t = line.split()
            if not t:
                continue
            if t[0] == 'LAYER' and len(t) == 2 and cur is None:
                cur = {'name': t[1], 'type': None, 'width': None, 'pitch': None}
            elif cur is not None:
                if t[0] == 'END' and len(t) > 1 and t[1] == cur['name']:
                    if cur['type'] in ('ROUTING', 'CUT'):
                        out.append(cur)
                    cur = None
                elif t[0] == 'TYPE':
                    cur['type'] = t[1]
                elif t[0] == 'WIDTH' and len(t) == 3 and t[2] == ';' and cur['width'] is None:
                    cur['width'] = float(t[1])
                elif t[0] == 'PITCH' and cur['pitch'] is None:
                    cur['pitch'] = float(t[1])
            if t[0] == 'MACRO':
                break
    return out


def captable(path):
    lay, via, cap = {}, {}, {}
    sec, cur, key, rows = None, None, None, []
    with open(path) as f:
        lines = [l.rstrip('\n') for l in f]
    i = 0
    while i < len(lines):
        t = lines[i].split()
        i += 1
        if not t or t[0].startswith('#'):
            continue
        if t[0] == 'BASIC_CAP_TABLE':
            sec = 'basic'; cur = None; continue
        if t[0] == 'END_BASIC_CAP_TABLE':
            sec = None; continue
        if t[0] == 'EXTENDED_CAP_TABLE':
            break
        if sec == 'basic':
            if len(t) == 1:
                cur = t[0]; cap[cur] = []
            elif re.match(r'^[0-9.]+$', t[0]) and cur:
                cap[cur].append(tuple(float(x) for x in t[:3]))
            continue
        if t[0] == 'LAYER' and len(t) == 2:
            cur = {'kind': 'layer'}; lay[t[1]] = cur; key = None; continue
        if t[0] == 'VIA' and len(t) == 2:
            cur = {'kind': 'via'}; via[t[1]] = cur; key = None; continue
        if t[0] == 'END' and cur is not None:
            cur = None; continue
        if cur is None:
            continue
        if t[0] in ('Thickness', 'TopWidth', 'BottomWidth', 'MinWidth', 'Resistance'):
            cur[t[0]] = float(t[1]); key = None
        elif t[0] in ('RhoWidths', 'RhoSpacings'):
            cur[t[0]] = [float(x) for x in t[1:]]
        elif t[0] == 'RhoValues':
            key = 'RhoValues'; cur[key] = [[float(x) for x in t[1:]]]
        elif key == 'RhoValues' and re.match(r'^[0-9.eE+-]+$', t[0]):
            cur[key].append([float(x) for x in t])
        else:
            key = None
    return lay, via, cap


def interp(xs, ys, x):
    if x <= xs[0]:
        return ys[0]
    for k in range(1, len(xs)):
        if x <= xs[k]:
            a = (x - xs[k - 1]) / (xs[k] - xs[k - 1])
            return ys[k - 1] + a * (ys[k] - ys[k - 1])
    return ys[-1]


def main():
    lef, cpt, corner, pre = sys.argv[1:5]
    layers = lef_layers(lef)
    lay, via, cap = captable(cpt)
    tcl = ['# set_layer_rc for corner %s from %s (generated by captable_rc.py)' % (corner, cpt.split('/')[-1])]
    txt = ['# layer type R_ohm_per_um C_fF_per_um width spacing | via R_ohm_per_cut  (corner %s)' % corner]
    for L in layers:
        n = L['name']
        if L['type'] == 'ROUTING' and n in lay and n in cap:
            p = lay[n]
            w = L['width'] or p['MinWidth']
            s = (L['pitch'] or 2 * w) - w
            rows = [r for r in cap[n] if abs(r[0] - min(cap[n], key=lambda r: abs(r[0] - w))[0]) < 1e-9]
            c = interp([r[1] for r in rows], [r[2] for r in rows], s)          # fF/um
            rho = p['RhoValues']                                                # rows: spacings, cols: widths
            col = [row[0] for row in rho]
            sp = p['RhoSpacings'][:len(col)]
            r_rho = interp(sp, col, s) if len(sp) == len(col) else col[0]
            weff = (p['TopWidth'] + p['BottomWidth']) / 2.0
            r = r_rho / (p['Thickness'] * weff)                                 # Ohm/um
            tcl.append('set_layer_rc -corner %s -layer %s -resistance %.6e -capacitance %.6e'
                       % (corner, n, r / 1000.0, c / 1000.0))
            txt.append('%s ROUTING %.6f %.6f %.3f %.3f' % (n, r, c, w, s))
        elif L['type'] == 'CUT' and n in via and 'Resistance' in via[n]:
            r = via[n]['Resistance']
            tcl.append('set_layer_rc -corner %s -via %s -resistance %.6e' % (corner, n, r / 1000.0))
            txt.append('%s CUT %.6f' % (n, r))
    with open(pre + '.tcl', 'w') as f:
        f.write('\n'.join(tcl) + '\n')
    with open(pre + '.txt', 'w') as f:
        f.write('\n'.join(txt) + '\n')


if __name__ == '__main__':
    main()

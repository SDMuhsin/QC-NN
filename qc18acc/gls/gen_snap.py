#!/usr/bin/env python3
"""Backdoor include of the QC18-ACC gate-level testbench (qa_tb +define+QA_GLS) from a DC netlist.

    gen_snap.py <qa_top.v> [v3|v4] > qa_gls_snap.svh

v4 (16 pixel rows): 48 x qa_act_256x128m2 (u_act/g_bank[k].g_buf[b].u_ram, rf_sp_adv mux 2: reg [255:0] mem [0:127],
word a in row a >> 1, bit b at 2 b + a % 2, function unmux2 of hw4/tb/qa_tb.sv) into snap[b*4096 + k*256 + a].

v3 (Kb = 2): 48 x qa_act_512x64m4 (u_act/g_buf[b].g_bank[k].g_half[h].u_ram, rf_sp_adv mux 4: reg [255:0]
mem [0:127], word a in row a >> 2, bit b at 4 b + a % 4, function unmux4 of hw3/tb/qa_tb.sv), into the 64-b half h
of snap[b*4096 + k*512 + a].

Finds every activation-bank macro (qa_act_1024x64m8) under qa_top by walking the netlist's module / instance
hierarchy, takes buffer / bank from the qa_sram instance name (u_act/g_buf[b].g_bank[k].u_ram, as DC
change_names spells it) and writes one always block per bank that copies the 1024 words of the ARM model
(reg [511:0] mem [0:127], column mux 8: word a in row a >> 3, bit b at 8 b + a % 8, function unmux8 of qa_tb)
into snap[] at a pass end, exactly like the RTL / QA_TECH paths of qa_tb.sv.
"""
import re
import sys

V3 = len(sys.argv) > 2 and sys.argv[2] == "v3"
V4 = len(sys.argv) > 2 and sys.argv[2] == "v4"
MACRO = "qa_act_256x128m2" if V4 else "qa_act_512x64m4" if V3 else "qa_act_1024x64m8"


def parse(path):
    mods, cur = {}, None
    inst = re.compile(r"^\s*([A-Za-z_][\w$]*)\s+(\\\S+|[A-Za-z_][\w$]*)\s*\(")
    with open(path) as f:
        for line in f:
            if line.startswith("module "):
                cur = line.split()[1].split("(")[0]
                mods[cur] = []
            elif line.startswith("endmodule"):
                cur = None
            elif cur is not None:
                m = inst.match(line)
                if m and m.group(1) not in ("input", "output", "inout", "wire", "assign", "module"):
                    mods[cur].append((m.group(1), m.group(2)))
    return mods


def walk(mods, mod, path, out):
    for ref, name in mods.get(mod, ()):
        if ref == MACRO:
            out.append(path + [name])
        elif ref in mods:
            walk(mods, ref, path + [name], out)


def ref(name):
    return name + " " if name.startswith("\\") else name


def main():
    mods = parse(sys.argv[1])
    paths = []
    walk(mods, "qa_top", [], paths)
    seen = set()
    print(f"// generated by qc18acc/gls/gen_snap.py from {sys.argv[1]}: {len(paths)} x {MACRO}")
    for p in paths:
        ram = next(n for n in p if "u_ram" in n)
        if V4:
            m = re.search(r"g_bank\D*(\d+)\D+g_buf\D*(\d+)", ram)
            if not m:
                sys.exit(f"gen_snap: cannot parse bank / buffer of {'/'.join(p)}")
            k, b = int(m.group(1)), int(m.group(2))
            seen.add((b, k))
            h = "dut." + ".".join(ref(n) for n in p)
            print(f"  always @(posedge clk) if (snap_go) for (int a = 0; a < ADEPTH; a++)\n"
                  f"    snap[{b}*4096 + {k}*256 + a] = unmux2({h}.mem[a >> 1], a % 2);")
            continue
        m = re.search(r"g_buf\D*(\d+)\D+g_bank\D*(\d+)" + (r"\D+g_half\D*(\d+)" if V3 else ""), ram)
        if not m:
            sys.exit(f"gen_snap: cannot parse buffer / bank of {'/'.join(p)}")
        b, k = int(m.group(1)), int(m.group(2))
        h = "dut." + ".".join(ref(n) for n in p)
        if V3:
            hf = int(m.group(3))
            seen.add((b, k, hf))
            print(f"  always @(posedge clk) if (snap_go) for (int a = 0; a < ADEPTH; a++)\n"
                  f"    snap[{b}*4096 + {k}*512 + a][{hf}*64 +: 64] = unmux4({h}.mem[a >> 2], a % 4);")
            continue
        seen.add((b, k))
        print(f"  always @(posedge clk) if (snap_go) for (int a = 0; a < ADEPTH; a++)\n"
              f"    snap[{b}*8192 + {k}*1024 + a] = unmux8({h}.mem[a >> 3], a % 8);")
    # flat netlist (OpenROAD write_verilog): no u_seq module instance, the TB's dut.u_seq.npass becomes the Q nets
    # of the escaped register instances \u_seq/npass_reg_<i>_
    q = {}
    pat = re.compile(r"^\s*\w+\s+\\u_seq/npass_reg_(\d+)_\s+\(\.\w+\(([^)]*)\)")
    with open(sys.argv[1]) as f:
        for line in f:
            if "npass_reg_" in line:
                m = pat.match(line)
                if m and ".Q(" in line:
                    q[int(m.group(1))] = re.search(r"\.Q\(([^)]*)\)", line).group(1).strip()
    if q:
        if sorted(q) != list(range(6)):
            sys.exit(f"gen_snap: flat netlist, npass registers {sorted(q)}")
        net = lambda n: ref(n.strip()) if n.startswith("\\") else n
        print("`define QA_NPASS {" + ", ".join(f"dut.{net(q[i])}" for i in range(5, -1, -1)) + "}")
    n = 48 if (V3 or V4) else 24
    if len(seen) != n or len(paths) != n:
        sys.exit(f"gen_snap: expected {n} activation macros, found {len(paths)} ({len(seen)} distinct)")


if __name__ == "__main__":
    main()

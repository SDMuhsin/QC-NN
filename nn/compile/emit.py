"""Emit the C side of a compiled Program: build/gen/nn_net.h and nn_net.c.

nn_net.c holds (all in the memory island): the step table, one nn_conv_t per GeMMX call, the
weight blobs (B layout + bias tiles), the padded input images, and the expected results
(per-step Fletcher checksums of every output tensor and the int32 logits of every image).
nn_full.c (linked only with -DNN_FULL_CHECK) holds every layer's expected int8 tensor of image 0.
"""
import os

import numpy as np

from .lower import ALIGN, TCDM_RESERVED, TCDM_SIZE

STREAMER_FIELDS = (
    "Aslstride0 Aslstride1 Atlbound0 Atlstride0 Atlbound1 Atlstride1 Atlbound2 Atlstride2 Atlbound3 "
    "Atlstride3 Atlbound4 Atlstride4 Atlbound5 Atlstride5 set_addr_remap_index_A "
    "Bslstride0 Bslstride1 Btlbound0 Btlstride0 Btlbound1 Btlstride1 Btlbound2 Btlstride2 set_addr_remap_index_B "
    "D8slstride0 D8slstride1 D8tlbound0 D8tlstride0 D8tlbound1 D8tlstride1 D8tlbound2 D8tlstride2 "
    "set_addr_remap_index_D8 "
    "Cslstride0 Cslstride1 Ctlbound0 Ctlstride0 Ctlbound1 Ctlstride1 Ctlbound2 Ctlstride2 set_addr_remap_index_C "
    "D32slstride0 D32slstride1 D32tlbound0 D32tlstride0 D32tlbound1 D32tlstride1 D32tlbound2 D32tlstride2 "
    "set_addr_remap_index_D32 "
    "delta_local_a delta_local_b delta_local_d8 delta_local_c delta_local_d32 "
    "bypassSIMD transposed_A transposed_B channel_en_C broadcast_C K N M").split()


def fletcher(t_int8):
    """Checksum of a tensor interior [C8][H][W][8] as computed by nn_cluster.c (uint32 words)."""
    w = np.ascontiguousarray(t_int8).view(np.uint32).reshape(-1).astype(np.uint64)
    s1 = np.cumsum(w) % 2 ** 32
    return int(s1[-1]), int(s1.sum() % 2 ** 32)


def u8(x): return int(x) & 0xFF


def conv_struct(c):
    vals = [str(int(c[f])) for f in STREAMER_FIELDS]
    sub = (u8(c["subtraction_b"]) << 8) | u8(c["subtraction_a"])
    csr0 = (u8(c["min_int_i"]) << 24) | (u8(c["max_int_i"]) << 16) | (u8(c["output_zp_i"]) << 8) | u8(c["input_zp_i"])
    sh = c["shift"]
    sh0 = sh[0] | sh[1] << 8 | sh[2] << 16 | sh[3] << 24
    sh1 = sh[4] | sh[5] << 8 | sh[6] << 16 | sh[7] << 24
    vals += [f"0x{sub:x}u", f"0x{csr0:x}u", str(c["double_round_i"]), f"0x{sh0:x}u", f"0x{sh1:x}u"]
    vals.append("{" + ", ".join(f"{m}" for m in c["multiplier"]) + "}")
    return "{" + ", ".join(vals) + "}"


def carray(ctype, name, data, align=ALIGN, per_line=24, section=None):
    data = list(data)
    attr = f" __attribute__((aligned({align})))" if align else ""
    if section:
        attr += f' __attribute__((section("{section}")))'
    lines = [", ".join(str(int(v)) for v in data[i:i + per_line]) for i in range(0, len(data), per_line)]
    return f"const {ctype} {name}[{len(data)}]{attr} = {{\n  " + ",\n  ".join(lines) + "\n};\n"


def emit(prog, images, ref_taps, ref_logits, outdir):
    """images: list of padded input byte strings; ref_taps: per image dict step name -> int8
    interior [C8][H][W][8]; ref_logits: [n, 10] int."""
    os.makedirs(outdir, exist_ok=True)
    n = len(images)
    S = prog.steps
    h = [
        "// Generated by nn/compile (python -m nn.compile.main). Do not edit.",
        "#ifndef NN_NET_H", "#define NN_NET_H", '#include "nn_types.h"',
        f"#define NN_N_IMAGES {n}", f"#define NN_N_STEPS {len(S)}", f"#define NN_N_BLOBS {len(prog.blobs)}",
        f"#define NN_N_CLASSES 10",
        f"#define NN_INPUT_ADDR {prog.tensors['input'].addr}u",
        f"#define NN_INPUT_SIZE {prog.tensors['input'].size}u",
        f"#define NN_TCDM_ARENA {prog.arena}u   // reserved top {TCDM_RESERVED} B: mailbox + stacks",
        f"#define NN_TCDM_PEAK {prog.peak}u",
        "extern const nn_step_t nn_steps[NN_N_STEPS];",
        "extern const nn_blob_t nn_blobs[NN_N_BLOBS];",
        "extern const uint8_t nn_images[NN_N_IMAGES][NN_INPUT_SIZE];",
        "extern const uint32_t nn_expect_chk[NN_N_IMAGES][NN_N_STEPS][2];",
        "extern const int32_t nn_expect_logits[NN_N_IMAGES][NN_N_CLASSES];",
        "extern const char *const nn_step_names[NN_N_STEPS];",
        "#ifdef NN_FULL_CHECK",
        "extern const int8_t *const nn_expect_full[NN_N_STEPS];   // image 0, [C8][H][W][8]",
        "#endif",
        "#endif", ""]
    open(os.path.join(outdir, "nn_net.h"), "w").write("\n".join(h))

    c = ["// Generated by nn/compile (python -m nn.compile.main). Do not edit.",
         "// TCDM plan (offsets from the cluster TCDM base):"]
    for t in sorted(list(prog.tensors.values()) + prog.blobs, key=lambda t: t.addr):
        c.append(f"//   0x{t.addr:05x} .. 0x{t.addr + t.size:05x}  {t.name:8s} live steps {t.live}")
    c += ['#include "nn_net.h"', ""]
    blob_idx = {}
    for i, b in enumerate(prog.blobs):
        blob_idx[b.name] = i
        c.append(carray("uint8_t", f"blob_{b.name}", np.frombuffer(b.data, np.uint8)))
    c.append("const nn_blob_t nn_blobs[NN_N_BLOBS] = {")
    for b in prog.blobs:
        c.append(f"  {{blob_{b.name}, {b.addr}u, {b.size}u, {b.issue}u}},  // {b.name}")
    c.append("};\n")
    T = prog.tensors
    for st in S:
        if st.kind == "conv":
            c.append(f"static const nn_conv_t p_{st.name} = {conv_struct(st.cfg)};")
        elif st.kind == "add":
            v, ta, tb, to = st.cfg, T[st.ins[0]], T[st.ins[1]], T[st.out]
            ins = lambda t: t.addr + t.offset(0, 1, 1)
            c.append(f"static const nn_add_t p_{st.name} = {{{ins(ta)}u, {ins(tb)}u, {ins(to)}u, "
                     f"{v['za']}, {v['ma']}, {v['zb']}, {v['mb']}, {v['zo']}, {v['lo']}, {to.C8}u, {to.H}u, {to.Wp}u}};")
        elif st.kind == "poolfc":
            t = T["add3"]
            c.append(f"static const nn_poolfc_t p_{st.name} = {{{t.addr + t.offset(0, 1, 1)}u, {t.C8}u, {t.H}u, "
                     f"{t.Wp}u, {st.cfg['zp_in']}, {st.blob.addr}u, {st.blob.addr + st.cfg['bias_off']}u, 10u, 64u}};")
    c.append("\nconst nn_step_t nn_steps[NN_N_STEPS] = {")
    kinds = dict(input="NN_INPUT", conv="NN_CONV", add="NN_ADD", poolfc="NN_POOLFC")
    for st in S:
        p = f"&p_{st.name}" if st.kind != "input" else "0"
        bi = blob_idx[st.blob.name] if st.blob else -1
        if st.out:
            t = T[st.out]
            zp = t.zp if (t.border and st.kind != "input") else 999
            o = f"{t.addr + t.offset(0, 1, 1)}u, {t.C8}u, {t.H}u, {t.Wp}u, {zp}"
        else:
            o = "0u, 0u, 0u, 0u, 999"
        c.append(f"  {{{kinds[st.kind]}, {bi}, {p}, {o}}},  // {st.idx} {st.name}")
    c.append("};")
    c.append("const char *const nn_step_names[NN_N_STEPS] = {" + ", ".join(f'"{s.name}"' for s in S) + "};\n")
    c.append(f"const uint8_t nn_images[NN_N_IMAGES][NN_INPUT_SIZE] __attribute__((aligned({ALIGN}))) = {{")
    for img in images:
        c.append("  {" + ", ".join(str(v) for v in img) + "},")
    c.append("};\n")
    chk = []
    for i in range(n):
        row = []
        for st in S:
            row.append(fletcher(ref_taps[i][st.out]) if st.out else (0, 0))
        chk.append("  {" + ", ".join(f"{{0x{a:08x}u, 0x{b:08x}u}}" for a, b in row) + "}")
    c.append("const uint32_t nn_expect_chk[NN_N_IMAGES][NN_N_STEPS][2] = {\n" + ",\n".join(chk) + "\n};")
    c.append("const int32_t nn_expect_logits[NN_N_IMAGES][NN_N_CLASSES] = {\n" +
             ",\n".join("  {" + ", ".join(str(int(v)) for v in l) + "}" for l in ref_logits) + "\n};")
    open(os.path.join(outdir, "nn_net.c"), "w").write("\n".join(c) + "\n")

    f = ["// Generated: expected int8 output of every step for image 0 ([C8][H][W][8]).",
         '#include "nn_net.h"', "#ifdef NN_FULL_CHECK"]
    for st in S:
        if st.out:
            f.append(carray("int8_t", f"full_{st.name}", ref_taps[0][st.out].reshape(-1), align=8))
    f.append("const int8_t *const nn_expect_full[NN_N_STEPS] = {" +
             ", ".join(f"full_{s.name}" if s.out else "0" for s in S) + "};")
    f.append("#endif")
    open(os.path.join(outdir, "nn_full.c"), "w").write("\n".join(f) + "\n")
    blob_bytes = sum(b.size for b in prog.blobs)
    return dict(blob_bytes=blob_bytes, image_bytes=n * len(images[0]),
                full_bytes=sum(ref_taps[0][s.out].size for s in S if s.out))

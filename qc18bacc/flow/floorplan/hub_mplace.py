#!/usr/bin/env python3
"""Hub qb_hub floorplan (results/r9b.md, r10b.md, r15.md, r22.md): macro placement, die and core of the south hub, in chip
x coordinates (die x 0 .. 3990: west strip 0-860 + 8 columns of 390 um from x0 = 860), die y 0 .. H.
    python3 -I hub_mplace.py <macros.txt> <out.tcl> <SB>
Three stages (one file for what impl/r10b/mplace10.py -> r15/mplace15.py -> r22/mplace22.py made in a chain):
  base  params row (8 macros P, MX, right-aligned to the array east edge, 10-um gaps) at the core bottom, B row (one per
        column, MX), 4 S rows (R0, pitch S height + CH around the columns), channels CH 40; logic band SB um above the
        last S row fixes the die height H.  South-west corner: FC (R90), IMG x 4 stacked (MX) east of it, params 8 (R0)
        above FC.
  mid   one logic band between S rows 1 | 2: S rows 2 and 3 move north, S row 3 top at the core top minus NG
        (NG = PS + P height + G, the room of the params row of 'pn')
  pn    "params north": the 8 column params macros move to the north edge (MX: pins on the macro's north edge, facing the
        north-edge pf / pw column pins), with a prm logic band of G 110 um between the P row and the core top; S row 3
        PS 10 um under the P row; B / S0 / S1 / FC / IMG / params 8 shift south by the vacated P row + channel; S row 2
        moves to the south side (MX, pins up), S12 10 um above S1 (S2S: S3 reads / writes no longer cross S2)
<out.tcl>: P(DIE_AREA), P(CORE_AREA), P(MACRO_PLACE), ::QB9_H, ::QB9_X0 (array west edge), ::QB15_BANDS {name y0 y1 ...}.
(The header comment and the band list are kept as the chain wrote them: the generated file is byte-identical.)"""
import math
import re
import sys

mac, out, SB = sys.argv[1], sys.argv[2], float(sys.argv[3])

# ---- base (impl/r10b/mplace10.py, QB_P8SLOT -1 = the R9b params layout)
M, WEST, CH, HG = 10.0, 850.0, 40.0, 10.0
BW, NC = 390.0, 8
ROWH, SITE, CY0 = 1.8, 0.2, 5.0
snapx = lambda v: round(round(v / SITE) * SITE, 3)
snapy = lambda v: round(CY0 + round((v - CY0) / ROWH + 0.4999) * ROWH, 3)
inst = {}
for ln in open(mac):
    n, m, w, h = ln.split(); inst.setdefault(m, []).append((n, float(w), float(h)))
idx = lambda n, *ks: tuple(int(re.search(k + r'_?(\d+)_', n).group(1)) for k in ks)
dim = {m: v[0][1:] for m, v in inst.items()}
place = []
put = lambda n, x, y, o: place.append((n, snapx(x), snapy(y), o))
x0 = M + WEST
xr = x0 + NC * BW
dieW = snapx(xr + M)
P = sorted(inst['qb_p_240x144m2'], key=lambda t: idx(t[0], 'g_pm'))
pw, ph = dim['qb_p_240x144m2']
xs = xr - (8 * (pw + HG) - HG)
assert xs >= 5.0, ('params row wider than the core', xs)
y = M
for s_, k in enumerate(range(8)):
    x = xs + s_ * (pw + HG)
    put(P[k][0], x, y, 'MX')
    cx = x + pw / 2; tgt = x0 + BW * k + BW / 2
    print('MPLACE10 params %d slot %d x %.1f centre %.1f %s' % (k, s_, x, cx, 'col offset %+.1f' % (cx - tgt)))
y = snapy(y + ph + CH)
ysw = y
Bm = sorted(inst['qb_b_128x128m1'], key=lambda t: idx(t[0], 'g_map', 'g_mm'))
bw, bh = dim['qb_b_128x128m1']
for c, (n, _, _) in enumerate(Bm): put(n, x0 + c * BW + (BW - bw) / 2, y, 'MX')
y = snapy(y + bh + CH)
S = sorted(inst['qb_s_256x128m1'], key=lambda t: idx(t[0], 'g_s'))
sw, sh = dim['qb_s_256x128m1']
for r in range(4):
    for c in range(8):
        put(S[8 * r + c][0], x0 + c * BW + (BW - sw) / 2 + (sw + HG - BW) * (c - 3.5), y, 'R0')
    y = snapy(y + sh + CH)
H = round(snapy(y - CH + SB) + 0.0, 3)
fw, fh = dim['qb_f_3232x128m8']
put(inst['qb_f_3232x128m8'][0][0], M, ysw, 'R90')
I = sorted(inst['qb_i_128x128m1'], key=lambda t: idx(t[0], 'g_img'))
iw, ih = dim['qb_i_128x128m1']
xi = M + fh + 2 * HG
for k, (n, _, _) in enumerate(I): put(n, xi, ysw + k * (ih + HG), 'MX')
yp9 = snapy(ysw + fw + HG)
put(P[8][0], M, yp9, 'R0')
print('MPLACE10 params 8 north-west x %.1f y %.1f (R9b)' % (M, yp9))
assert yp9 + ph <= H - 5, ('params 9 above the die', yp9 + ph, H)
assert ysw + fw <= H - 5, ('FC above the die', ysw + fw, H)
assert len(place) == sum(len(v) for v in inst.values())
t = '# generated by impl/r9b/mplace9.py (CH %g SB %g)\n' % (CH, SB)
t += 'set P(DIE_AREA) {0 0 %.1f %.3f}\nset P(CORE_AREA) {5 5 %.1f %.3f}\n' % (dieW, H, dieW - 5, H - 5)
t += 'set P(MACRO_PLACE) {\n' + ''.join('  {%s %.3f %.3f %s}\n' % ((p[0].replace('\\', '\\\\'),) + p[1:]) for p in place) + '}\n'
t += 'set ::QB9_H %.3f\nset ::QB9_X0 %.1f\n' % (H, x0)
print('MPLACE9 hub die %.1f x %.3f um = %.3f mm2, %d macros, S top %.1f, band %.0f' % (dieW, H, dieW * H / 1e6, len(place), y - CH, SB))

# ---- mid (impl/r15/mplace15.py QB15_FP mid, QB15_NG from the pn stage)
G, PS, S12 = 110.0, 10.0, 10.0
NG = float('%.3f' % (PS + ph + G))
pl = re.search(r'set P\(MACRO_PLACE\) \{\n(.*?)\n\}', t, re.S)
rows = [ln.strip()[1:-1].split() for ln in pl.group(1).split('\n')]
srow = lambda n: (lambda m: int(m.group(1)) // 8 if m else None)(re.search(r'g_s_(\d+)__u_m', n))
ys = sorted({float(r[2]) for r in rows if srow(r[0]) is not None})
assert len(ys) == 4, ys
s1top = ys[1] + sh
ctop = H - 5.0 - NG
gmax = ctop - (2 * sh + CH) - s1top                    # largest S1 | S2 gap with S row 3 under the core top
y2 = s1top + gmax
y2 = snapy(y2) if snapy(y2) + 2 * sh + CH <= ctop + 1e-6 else round(snapy(y2) - 1.8, 3)   # snap down to a row
y3 = snapy(y2 + sh + CH)
if y3 + sh > ctop + 1e-6: y3 = round(y3 - 1.8, 3)
assert y3 + sh <= H - 5.0 + 1e-6 and y2 >= s1top, (y2, y3, s1top, H)
newy = {0: ys[0], 1: ys[1], 2: y2, 3: y3}
body = []
for r in rows:
    k = srow(r[0])
    if k is not None:
        r = [r[0], r[1], '%.3f' % newy[k], r[3]]
    body.append('  {%s}' % ' '.join(r))
t = t[:pl.start(1)] + '\n'.join(body) + t[pl.end(1):]
bands = [('S0', ys[0], ys[0] + sh), ('S1', ys[1], ys[1] + sh), ('S2', y2, y2 + sh), ('S3', y3, y3 + sh)]
lb = [('band_mid', s1top, y2)] if y2 - s1top > CH + 1 else []
if H - 5 - (y3 + sh) > CH + 1: lb.append(('band_top', y3 + sh, H))
bands += lb
t = t.replace('# generated by impl/r9b/mplace9.py', '# generated by impl/r15/mplace15.py (QB15_FP mid) from impl/r9b/mplace9.py')
t += 'set ::QB15_BANDS {%s}\n' % ' '.join('%s %.1f %.1f' % b for b in bands)
for b in bands: print('MPLACE15 band %s %.1f %.1f (%.1f um)' % (b + (b[2] - b[1],)))
print('MPLACE15 mid die %.1f x %.3f um = %.3f mm2, S rows y %s, logic band(s) %s um' % (
    dieW, H, dieW * H / 1e6, ' '.join('%.1f' % newy[k] for k in range(4)), ' + '.join('%.0f' % (b[2] - b[1]) for b in lb)))

# ---- pn (impl/r22/mplace22.py QB22_FP pn, QB22_S2S 1)
H = float(re.search(r'set ::QB9_H ([\d.]+)', t).group(1))
pl = re.search(r'set P\(MACRO_PLACE\) \{\n(.*?)\n\}', t, re.S)
rows = [ln.strip()[1:-1].split() for ln in pl.group(1).split('\n')]
pidx = lambda n: (lambda m: int(m.group(1)) if m else None)(re.search(r'g_pm_?(\d+)_', n))
isS = lambda n: re.search(r'g_s_(\d+)__u_m', n) is not None
srow = lambda n: int(re.search(r'g_s_(\d+)__u_m', n).group(1)) // 8
ys = sorted({float(r[2]) for r in rows if isS(r[0])})
yP = min(float(r[2]) for r in rows if pidx(r[0]) is not None and pidx(r[0]) < 8)
yB = min(float(r[2]) for r in rows if 'qb_b' in r[0] or re.search(r'g_map', r[0]))
dy = round(math.floor((yB - yP) / ROWH + 1e-6) * ROWH, 3)          # B row -> old P row y (row multiple)
ypn = CY0 + math.floor((H - CY0 - G - ph - CY0) / ROWH + 1e-6) * ROWH  # P row y (row grid, top <= core top - G)
s3top = ys[3] + dim['qb_s_256x128m1'][1]
assert s3top + PS <= ypn + 1e-6, (s3top, ypn)
snapu = lambda v: round(CY0 + math.ceil((v - CY0) / ROWH - 1e-6) * ROWH, 3)
y2s = snapu(ys[1] - dy + sh + S12)                                    # S2 on the south side
pos = {}
for r in rows:
    n, x, y, o = r[0], float(r[1]), float(r[2]), r[3]
    k = pidx(n)
    if k is not None and k < 8:
        y, o = ypn, 'MX'
    elif isS(n) and srow(n) == 2:
        y, o = y2s, 'MX'
    elif y < ys[2] or k == 8:                                         # south group: B, S0, S1, FC, IMG, params 8
        y = round(y - dy, 3)
    pos[n] = [x, y, o]
body = ['  {%s %.3f %.3f %s}' % (n, v[0], v[1], v[2]) for n, v in pos.items()]
t = t[:pl.start(1)] + '\n'.join(body) + t[pl.end(1):]
bands = [('S0', ys[0] - dy, ys[0] - dy + sh), ('S1', ys[1] - dy, ys[1] - dy + sh), ('S2', y2s, y2s + sh),
         ('band_mid', y2s + sh, ys[3]), ('S3', ys[3], ys[3] + sh), ('prow', ypn, ypn + ph), ('prmband', ypn + ph, H - CY0)]
t = re.sub(r'set ::QB15_BANDS \{.*\}\n', 'set ::QB15_BANDS {%s}\n' % ' '.join('%s %.1f %.1f' % b for b in bands), t)
t = t.replace('(QB15_FP', '+ impl/r22/mplace22.py pn (QB15_FP', 1)
for b in bands: print('MPLACE22 band %s %.1f %.1f (%.1f um)' % (b + (b[2] - b[1],)))
lb = [b for b in bands if b[0] == 'band_mid'][0]
print('MPLACE22 pn (S2S 1 P0W 0): south shift %.1f, P row y %.1f MX, S3 top %.1f, prm band %.1f um, logic band %.1f um' % (
    dy, ypn, s3top, H - CY0 - ypn - ph, lb[2] - lb[1]))
open(out, 'w').write(t)
print('MPLACE22 pn written %s' % out)

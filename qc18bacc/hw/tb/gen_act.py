#!/usr/bin/env python3
"""Writes hw/rtl/qb_act_net.sv: the patch network of qb_act (line buffer -> S1 chunk slice -> act port) and the
int8 all-zero-patch flags, generated from the configuration table below; prints the mux statistics.
    python3 qc18bacc/hw/tb/gen_act.py

Line buffer (LB): 8 slots x 2048 b, slot s = window row s, row layout chunk-major (compile/layout.py): 32-b group
G = g W + x holds channels 32 g .. 32 g + 31 of pixel x.  All networks work on 32-b groups.
S1 (registered, dynamic): S1 group (s, x) <- LB group (s, g W + x) for the current chunk g (3x3), or a static
  1x1 gather (s, xs = t W / 2 + x_in / 2) <- LB group (s, t W + x_in).  One-hot select lines sel1:
  3x3: line LB3[W] + g (W 32: 2, 16: 4, 8: 8, 4: 16 lines = 30), 1x1: 30 + {cfg 3, 6, 9}.  No line = zero item.
S2 (registered = act, static per pass / tile phase): act unit (r, t) = 32 b of row r, tap t (3x3: byte 4 t + q,
  channels 32 g + 8 q ..; 1x1: channels 32 t ..) <- S1 group or 0 (zero padding), one-hot cfg lines sel2[11].
cfg  W  s k  rows/tile  window base (slot 0)                 used by
 0  32 1 3  1 (x 0-15)  oy - 1 (pad rows zero-loaded)        b0 / b1 c1 c2, stem
 1  32 1 3  1 (x 16-31) oy - 1                               (odd tiles of cfg 0)
 2  32 2 3  1           2 oy - 1                             b2.c1
 3  32 2 1  1           2 oy (odd rows not loaded)           b2.sc
 4  16 1 3  1           oy - 1                               b2.c2, b3
 5  16 2 3  2           2 oy0 - 1                            b4.c1
 6  16 2 1  2           2 oy0                                b4.sc
 7   8 1 3  2           oy0 - 1                              b4.c2, b5
 8   8 2 3  4 (map)     0, row -1 static zero                b6.c1 (HQ planes)
 9   8 2 1  4 (map)     0                                    b6.sc (HQ planes)
10   4 1 3  4 (map)     0, rows -1 / 4 static zero           b6.c2 (Z planes), b7
"""
import os
from collections import defaultdict

CFG = {0: (32, 1, 3, 0), 1: (32, 1, 3, 16), 2: (32, 2, 3, 0), 3: (32, 2, 1, 0), 4: (16, 1, 3, 0), 5: (16, 2, 3, 0),
       6: (16, 2, 1, 0), 7: (8, 1, 3, 0), 8: (8, 2, 3, 0), 9: (8, 2, 1, 0), 10: (4, 1, 3, 0)}
STATIC = {8, 9, 10}                       # whole-map tiles: slot = input row, out-of-map rows are constant zero
LB3 = {32: 0, 16: 2, 8: 6, 4: 14}         # first S1 select line of a 3x3 W class
K1 = {3: 30, 6: 31, 9: 32}
NSEL1, NCFG, ROWS, TAPS = 33, 11, 16, 9
FLAGS = {8: 8, 9: 1, 10: 16}              # int8 configs: chunk flags


def build():
    s2 = defaultdict(lambda: defaultdict(set))        # act unit u -> S1 pos -> {cfg}
    s1 = defaultdict(lambda: defaultdict(set))        # S1 pos (slot, x) -> LB group -> {sel1 line}
    use = defaultdict(set)                            # (cfg, g) -> LB groups read by the act of that cfg / chunk
    for cfg, (W, s, k, x0) in CFG.items():
        Wout = W // s
        C = 2048 // W
        for r in range(ROWS):
            if W == 32 and s == 1:
                oyr, ox = 0, x0 + r
            else:
                oyr, ox = divmod(r, Wout)
            for t in range(TAPS):
                u = r * TAPS + t
                if k == 3:
                    dy, dx = divmod(t, 3)
                    iy, ix = s * oyr + dy - 1, s * ox + dx - 1
                    slot = iy if cfg in STATIC else s * oyr + dy
                    if ix < 0 or ix >= W or (cfg in STATIC and (iy < 0 or iy >= W)):
                        continue
                    assert 0 <= slot < 8
                    pos = (slot, ix)
                    s2[u][pos].add(cfg)
                    for g in range(C // 32):
                        G = slot * 64 + g * W + ix
                        s1[pos][G].add(LB3[W] + g)
                        use[cfg, g].add(G)
                else:
                    if t >= C // 32:
                        continue
                    slot, xin = s * oyr, s * ox
                    pos = (slot, t * (W // 2) + xin // 2)
                    assert pos[1] < 32
                    s2[u][pos].add(cfg)
                    G = slot * 64 + t * W + xin
                    s1[pos][G].add(K1[cfg])
                    use[cfg, 0].add(G)
    return s1, s2, use


def main():
    s1, s2, use = build()
    pos = sorted(s1)
    idx = {p: i for i, p in enumerate(pos)}
    S1W = 32 * len(pos)
    L = ["// GENERATED by qc18bacc/hw/tb/gen_act.py -- do not edit.  Patch network of qb_act (see gen_act.py header).",
         f"// S1: {len(pos)} groups x 32 b; act: {ROWS} rows x {TAPS} units x 32 b; flags of the int8 configs.",
         "// qba_s1: chunk select LB -> S1 (registered); qba_s2: S1 -> act (registered); qba_flg: group ORs + flags.",
         "module qba_s1 (",
         "    input  logic                    clk,",
         "    input  logic [16383:0]          lb,     // 8 slots x 2048 b (slot s = bits 2048 s ..)",
         f"    input  logic [{NSEL1 - 1}:0]             sel1,   // one-hot S1 select (registered)",
         f"    output logic [{S1W - 1}:0]          s1);",
         f"    logic [{S1W - 1}:0] s1_d;",
         "    always_ff @(posedge clk) s1 <= s1_d;"]
    n1 = []
    for p in pos:
        terms = []
        for G, lines in sorted(s1[p].items()):
            cond = " | ".join(f"sel1[{l}]" for l in sorted(lines))
            terms.append(f"({{32{{{cond}}}}} & lb[{32 * G} +: 32])")
        n1.append(len(s1[p]))
        L.append(f"    assign s1_d[{32 * idx[p]} +: 32] = {' | '.join(terms)};   // slot {p[0]} x {p[1]}")
    L += ["endmodule", "",
          "module qba_s2 (",
          "    input  logic                    clk,",
          f"    input  logic [{S1W - 1}:0]          s1,",
          f"    input  logic [{NCFG - 1}:0]             sel2,   // one-hot cfg (registered)",
          "    output logic [4607:0]           act);   // row r: bits 288 r + 32 t + k",
          "    logic [4607:0] act_d;",
          "    always_ff @(posedge clk) act <= act_d;"]
    n2 = []
    for u in range(ROWS * TAPS):
        terms = []
        for p, cfgs in sorted(s2[u].items()):
            cond = " | ".join(f"sel2[{c}]" for c in sorted(cfgs))
            terms.append(f"({{32{{{cond}}}}} & s1[{32 * idx[p]} +: 32])")
        n2.append(len(s2[u]))
        L.append(f"    assign act_d[{32 * u} +: 32] = {' | '.join(terms) if terms else chr(39) + '0'};"
                 f"   // row {u // TAPS} unit {u % TAPS}")
    L += ["endmodule", "",
          "module qba_flg (",
          "    input  logic                    clk,",
          "    input  logic [16383:0]          lb,",
          "    output logic [7:0]              f8,     // cfg 8: chunk g patch nonzero",
          "    output logic                    f9,",
          "    output logic [15:0]             f10);",
          "    logic [511:0] gor;                      // registered OR of each LB 32-b group (slot * 64 + G)",
          "    always_ff @(posedge clk) for (int G = 0; G < 512; G++) gor[G] <= |lb[32 * G +: 32];"]
    nf = []
    for cfg, n in FLAGS.items():
        for g in range(n):
            gs = sorted(use[cfg, g])
            nf.append(len(gs))
            lhs = "f9" if cfg == 9 else f"f{cfg}[{g}]"
            L.append(f"    assign {lhs} = |{{{', '.join(f'gor[{G}]' for G in gs)}}};")
    L += ["endmodule", ""]
    out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "rtl", "qb_act_net.sv")
    open(out, "w").write("\n".join(L))
    # ---- statistics: candidate sources per bit, total and dynamic within one configuration
    dyn = {}
    for cfg, (W, s, k, x0) in CFG.items():
        dyn[cfg] = (2048 // W // 32) if k == 3 else 1
    hist = lambda v: {k: v.count(k) for k in sorted(set(v))}
    print(f"wrote {os.path.relpath(out)}: S1 {len(pos)} groups ({32 * len(pos)} flops), act 4608 b")
    print(f"S1 sources per bit (all cfgs): max {max(n1)} hist {hist(n1)}; dynamic within one cfg: "
          + ", ".join(f"cfg{c} {d}:1" for c, d in dyn.items()))
    print(f"act sources per bit (all cfgs, + zero): max {max(n2)} hist {hist(n2)}; within one cfg: 1 (static)")
    print(f"flag OR widths (32-b groups): {nf}")


if __name__ == "__main__":
    main()

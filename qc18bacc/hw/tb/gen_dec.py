#!/usr/bin/env python3
"""Writes hw/rtl/qb_dec.sv: the 8-b block code -> 10-b PE code decoder of qb_core (table = compile/program.py DEC;
129 legal codes, illegal codes 129..255 decode to 0 = no term).
    python3 qc18bacc/hw/tb/gen_dec.py
"""
import os
import sys

sys.path.insert(0, os.path.abspath(os.path.join(os.path.dirname(__file__), "..", "..", "..")))
from qc18bacc.compile.program import DEC  # noqa: E402

out = os.path.join(os.path.dirname(__file__), "..", "rtl", "qb_dec.sv")
lines = ["// GENERATED by qc18bacc/hw/tb/gen_dec.py from qc18bacc.compile.program.DEC -- do not edit.",
         "// qbc_dec: 8-b QC block code -> 10-b PE code {k1[2:0], t1[1:0], k2[2:0], t2[1:0]} (trit 01 = +1, 11 = -1,",
         "// 00 = 0); 129 legal codes (0 = empty block), illegal codes 129..255 -> 0 (no term).",
         "module qbc_dec (input logic [7:0] code, output logic [9:0] pe);",
         "    always_comb begin",
         "        case (code)"]
for i, v in enumerate(DEC):
    if v >= 0:
        lines.append(f"            8'd{i}: pe = 10'h{int(v):03x};")
lines += ["            default: pe = 10'h000;", "        endcase", "    end", "endmodule", ""]
open(out, "w").write("\n".join(lines))
print("wrote", os.path.relpath(out), sum(1 for v in DEC if v >= 0), "legal codes")

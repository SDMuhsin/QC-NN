#!/usr/bin/env python3
"""R35: IO pin geometry of an existing block abstract LEF -> OpenROAD place_pin commands (so a re-run of the block keeps
the pin positions every neighbour was built against, e.g. the r5b_blk column that the hub / act pins were aligned to).
usage: colpins.py <block.lef> <out.tcl>   (first RECT of each PIN, LEF coordinates = die coordinates, origin 0 0)"""
import sys
src, dst = sys.argv[1], sys.argv[2]
pins, cur, layer, use = {}, None, None, {}
for line in open(src):
    s = line.split()
    if not s: continue
    if s[0] == 'PIN': cur = s[1]; layer = None; continue
    if cur is None: continue
    if s[0] == 'USE': use[cur] = s[1].rstrip(';')
    elif s[0] == 'LAYER': layer = s[1]
    elif s[0] == 'RECT' and cur not in pins: pins[cur] = (layer, *map(float, s[1:5]))
    elif s[0] == 'END' and len(s) > 1 and s[1] == cur: cur = None
n = 0
with open(dst, 'w') as o:
    o.write('# generated by impl/r35/colpins.py from %s\n' % src)
    for p, (l, x0, y0, x1, y1) in pins.items():
        if use.get(p) in ('POWER', 'GROUND'): continue
        nm = p.replace('[', '\\[').replace(']', '\\]')
        o.write('place_pin -pin_name "%s" -layer %s -location {%.4f %.4f} -pin_size {%.4f %.4f}\n'
                % (nm, l, (x0 + x1) / 2, (y0 + y1) / 2, x1 - x0, y1 - y0))
        n += 1
sys.stderr.write('colpins: %d signal pins, layers %s\n' % (n, sorted({v[0] for v in pins.values()})))

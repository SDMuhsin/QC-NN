#!/usr/bin/env python3
"""R11 top floorplan (results/r11.md) + block-to-block interface check.
Geometry (um, chip coordinates, lower-left origin; mplace-style, impl/r6b/mplace.py constants):
  hub     qb_hub at (0, 0), 3990 x yh (R10b hub floorplan: south band of the chip, full width)
  array   8 x qb_col_blk 390 x 3110 abutted, x0 = 860 (= the hub's x0), y = yh (south pins on the hub's north pins)
  act     qb_act2_blk W x H at (x0 - W, yh + 3110 - H): east edge on column 0's west edge (R9a QB7_YOFF rule)
  north   logic band NB [QB_NB 120], 6 weight rows of 8 right-aligned (slot c = lanes 2c, 2c+1; R6b rule)
  NW      descriptors (R90) side by side at x M, y = weight band bottom; sequencer / glue std cells: west strip,
          NW corner, hub-to-act gap (gpl)
    python3 -I fp11.py <macros.txt> <abs dir> <out mplace.tcl> [col.lef] [top_bpins.txt]
Out: mplace.tcl (P(DIE_AREA), P(CORE_AREA), P(MACRO_PLACE), ::QB11_*), <out dir>/iface.txt (interface table)."""
import os
import re
import sys
from collections import defaultdict
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from lefio import read_macro

E = lambda k, d: float(os.environ.get(k, d))
mtxt, absd, outp = sys.argv[1:4]
colef = sys.argv[4] if len(sys.argv) > 4 else None
bpf = sys.argv[5] if len(sys.argv) > 5 else None
M, HG, CH, NB = 10.0, 10.0, 40.0, E("QB_NB", 120)
BW, BH, NC, x0 = 390.0, 3110.0, 8, 860.0
ROWH, SITE, CY0 = 1.8, 0.2, 0.0
snapx = lambda v: round(round(v / SITE) * SITE, 3)
snapy = lambda v: round(CY0 + round((v - CY0) / ROWH + 0.4999) * ROWH, 3)
inst = {}
for ln in open(mtxt):
    n, m, w, h = ln.split(); inst.setdefault(m, []).append((n, float(w), float(h)))
dim = {m: v[0][1:] for m, v in inst.items()}
idx = lambda n, *ks: tuple(int(re.search(k + r"_?(\d+)_", n).group(1)) for k in ks)
_, hW, yh, _ = read_macro(os.path.join(absd, "qb_hub.lef"))
_, aW, aH, _ = read_macro(os.path.join(absd, "qb_act2_blk.lef"))
place, org = [], {}
def put(n, x, y, o, snap=True):
    x, y = (snapx(x), snapy(y)) if snap else (round(x, 3), round(y, 3))
    place.append((n, x, y, o)); org[n] = (x, y)
put(inst["qb_hub"][0][0], 0.0, 0.0, "R0", False)
for c in range(NC):
    put([t for t in inst["qb_col_blk"] if idx(t[0], "g_c")[0] == c][0][0], x0 + c * BW, yh, "R0", False)
ya_act = yh + BH - aH
put(inst["qb_act2_blk"][0][0], x0 - aW, ya_act, "R0", False)
yt = yh + BH
ww, wh = dim["qb_w_204x144m2"]
W = sorted(inst["qb_w_204x144m2"], key=lambda t: idx(t[0], "g_wl", "g_wd"))
xr = x0 + NC * BW
xw = xr - (8 * (ww + HG) - HG)
y = snapy(yt + NB); yn = y; rows = []
for r in range(6):
    rows.append((y, "R0" if r % 2 == 0 else "MX"))
    y = snapy(y + wh + (HG if r % 2 == 0 else CH))
for n, _, _ in W:
    l, d = idx(n, "g_wl", "g_wd")
    c, r = l // 2, 3 * (l % 2) + d
    put(n, xw + c * (ww + HG), rows[r][0], rows[r][1])
top = snapy(y - CH + HG)
dw, dh = dim["qb_d_624x80m8"]
D = sorted(inst["qb_d_624x80m8"])
# NW corner west of the weight band: descriptors R90 (dh wide, dw tall) side by side from y = yn
for j, (n, _, _) in enumerate(D):
    put(n, M + j * (dh + HG), yn, "R90")
assert M + len(D) * (dh + HG) <= xw - HG, ("descriptors overlap the weight band", M + len(D) * (dh + HG), xw)
top = max(top, snapy(yn + dw + HG))
dieW, dieH = 3990.0, round(top + M, 1)
assert len(place) == sum(len(v) for v in inst.values()), (len(place), sum(len(v) for v in inst.values()))
A = dieW * dieH / 1e6
with open(outp, "w") as f:
    f.write("# generated by impl/r11/fp11.py\n")
    # core = die: the hub spans the full die width (gpl GPL-0120 rejects an instance wider than the core)
    f.write("set P(DIE_AREA) {0 0 %.1f %.1f}\nset P(CORE_AREA) {0 0 %.1f %.1f}\n" % (dieW, dieH, dieW, dieH))
    f.write("set P(MACRO_PLACE) {\n" + "".join("  {%s %.3f %.3f %s}\n" % ((p[0].replace("\\", "\\\\"),) + p[1:]) for p in place) + "}\n")
    f.write("set ::QB11_IOY {%.1f %.1f}\nset ::QB11_YH %.3f\nset ::QB11_YT %.3f\nset ::QB11_ACT {%.3f %.3f %.3f %.3f}\n"
            % (yt + 20, dieH - 20, yh, yt, x0 - aW, ya_act, x0, yt))
print("FP11 die %.1f x %.1f um = %.3f mm2 (f_tt needed for avg >= 1.3: 20.5 x A = %.0f MHz); hub 3990 x %.1f, array y %.1f..%.1f, "
      "act %.0f x %.0f at (%.1f, %.1f) (gap to the hub %.1f um), weights from y %.1f (x %.1f..%.1f), top %.1f"
      % (dieW, dieH, A, 20.5 * A, yh, yh, yt, aW, aH, x0 - aW, ya_act, ya_act - yh, yn, xw, xr, top))
# ------------------------------------------------------------------ interface check
if colef and bpf:
    geo = {"qb_hub": read_macro(os.path.join(absd, "qb_hub.lef"))[3], "qb_act2_blk": read_macro(os.path.join(absd, "qb_act2_blk.lef"))[3],
           "qb_col_blk": read_macro(colef)[3]}
    nets = defaultdict(list)
    for ln in open(bpf):
        i, m, p, n = ln.split()
        if m not in geo or n.startswith("SYNOPSYS_UNCONNECTED") or n.startswith("n_Logic") or p == "clk":
            continue
        g = geo[m].get(p)
        if g is None:
            nets[n].append((i, m, p, None)); continue
        ox, oy = org[i]
        nets[n].append((i, m, p, (g[1], ox + (g[2] + g[4]) / 2, oy + (g[3] + g[5]) / 2)))
    def tag(i):
        if "u_hub" in i: return "hub"
        if "u_act_blk" in i: return "act"
        return "col%d" % idx(i, "g_c")[0]
    T = defaultdict(lambda: [0, 0, 0.0, 0.0, 0, 0])   # nets, aligned, max dx, max dy, layer mismatch, missing pin
    BRK = defaultdict(lambda: [0, 0, 0, 0.0, 0.0])    # (interface, pin base) -> misaligned, layer!=, no pin, max dx, dy
    for n, l in nets.items():
        if len(l) < 2:
            continue
        drv = l[0]
        for a in range(len(l)):
            for b in range(a + 1, len(l)):
                p, q = l[a], l[b]
                if p[0] == q[0]:
                    continue
                k = "-".join(sorted((re.sub(r"\d", "", tag(p[0])) if tag(p[0]).startswith("col") and tag(q[0]).startswith("col") else tag(p[0]),
                                     tag(q[0]))))
                if tag(p[0]).startswith("col") and tag(q[0]).startswith("col"):
                    k = "col-col (abutted chain)"
                elif "hub" in k and "col" in k:
                    k = "col-hub"
                if k == "col-col (abutted chain)" and p[3] and q[3] and abs(p[3][1] - q[3][1]) > 1.2 and abs(p[3][2] - q[3][2]) < 0.011:
                    k = "col-col (same pin, top-driven)" if p[2] == q[2] else k
                t = T[k]; t[0] += 1
                bk = BRK[(k, re.sub(r"\[\d+\]$", "", (q if "u_col" in q[0] else p)[2]) + "/" + re.sub(r"\[\d+\]$", "", (p if "u_col" in q[0] else q)[2]))]
                if p[3] is None or q[3] is None:
                    t[5] += 1; bk[2] += 1; continue
                dx, dy = abs(p[3][1] - q[3][1]), abs(p[3][2] - q[3][2])
                if p[3][0] != q[3][0]:
                    t[4] += 1
                # abutted pins: same x (or same y), touching the shared edge (pin half-lengths <= 0.6 um)
                al = (dx < 0.011 and dy <= 1.2) or (dy < 0.011 and dx <= 1.2)
                t[1] += al
                if p[3][0] != q[3][0]:
                    bk[1] += 1
                if not al:
                    t[2] = max(t[2], dx); t[3] = max(t[3], dy)
                    bk[0] += 1; bk[3] = max(bk[3], dx); bk[4] = max(bk[4], dy)
    with open(os.path.join(os.path.dirname(outp), "iface.txt"), "w") as f:
        f.write("# R11 block-to-block interface (impl/r11/fp11.py): pin pairs on one top net\n")
        f.write("%-26s %8s %8s %8s %10s %10s %8s %8s\n" % ("interface", "pairs", "aligned", "misalign", "max_dx_um", "max_dy_um", "layer!=", "no_pin"))
        for k, t in sorted(T.items()):
            f.write("%-26s %8d %8d %8d %10.1f %10.1f %8d %8d\n" % (k, t[0], t[1], t[0] - t[1] - t[5], t[2], t[3], t[4], t[5]))
        f.write("# breakdown (interface, column-side pin / other pin base): misaligned, layer!=, no_pin, max dx, max dy\n")
        for (k, b), v in sorted(BRK.items(), key=lambda z: -(z[1][0] + z[1][1] + z[1][2])):
            if v[0] + v[1] + v[2]:
                f.write("  %-26s %-40s %6d %6d %6d %8.1f %8.1f\n" % (k, b, v[0], v[1], v[2], v[3], v[4]))
    print(open(os.path.join(os.path.dirname(outp), "iface.txt")).read())

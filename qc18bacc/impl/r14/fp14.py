#!/usr/bin/env python3
"""R14 top floorplan (results/r14.md), impl/r11/fp11.py geometry with the PI's west-strip decision:
  hub     qb_hub (abs14.py proxy, 3990 + X0 - 860 wide) at (0, 0)
  array   8 x qb_col_blk 390 x 3110 abutted, x0 = X0 [900], y = yh
  act     qb_act2_blk 900 x 1970 at (X0 - 900, yh + 3110 - 1970): TOP of the west strip, east edge on column 0
  gap     x 0..X0, y yh .. act bottom (1 140 um): sequencer / host registers + chip IO pins (west edge), hub clk pin,
          act south pins (controls + S / map read port straight above the hub's pins)
  north   band NB [QB_NB 120] + 6 weight rows (right-aligned to the array east edge), descriptors R90 in the NW corner
    python3 -I fp14.py <macros.txt> <abs dir> <out mplace.tcl>
Out: mplace.tcl (P(DIE_AREA), P(CORE_AREA), P(MACRO_PLACE), ::QB11_* for impl/r11/pins.tcl, ::QB14_*)."""
import os
import re
import sys
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "r11"))
from lefio import read_macro

E = lambda k, d: float(os.environ.get(k, d))
mtxt, absd, outp = sys.argv[1:4]
M, HG, CH, NB = 10.0, 10.0, 40.0, E("QB_NB", 120)
BW, BH, NC, x0 = 390.0, 3110.0, 8, E("QB14_X0", 900.0)
ROWH, SITE = 1.8, 0.2
snapx = lambda v: round(round(v / SITE) * SITE, 3)
snapy = lambda v: round(round(v / ROWH + 0.4999) * ROWH, 3)
inst = {}
for ln in open(mtxt):
    n, m, w, h = ln.split(); inst.setdefault(m, []).append((n, float(w), float(h)))
dim = {m: v[0][1:] for m, v in inst.items()}
idx = lambda n, *ks: tuple(int(re.search(k + r"_?(\d+)_", n).group(1)) for k in ks)
_, hW, yh, _ = read_macro(os.path.join(absd, "qb_hub.lef"))
_, aW, aH, _ = read_macro(os.path.join(absd, "qb_act2_blk.lef"))
place = []
def put(n, x, y, o, snap=True):
    x, y = (snapx(x), snapy(y)) if snap else (round(x, 3), round(y, 3))
    place.append((n, x, y, o))
# R35 opt-in QB14_HUBX [0]: hub at (HUBX, 0), die HUBX wider (real hub 3990 wide with its column pins at x 860 + 390 c)
HUBX = E("QB14_HUBX", 0.0)
put(inst["qb_hub"][0][0], HUBX, 0.0, "R0", False)
for c in range(NC):
    put([t for t in inst["qb_col_blk"] if idx(t[0], "g_c")[0] == c][0][0], x0 + c * BW, yh, "R0", False)
ya = yh + BH - aH; xa = x0 - aW
assert xa >= 0, xa
put(inst["qb_act2_blk"][0][0], xa, ya, "R0", False)
yt = yh + BH
ww, wh = dim["qb_w_204x144m2"]
W = sorted(inst["qb_w_204x144m2"], key=lambda t: idx(t[0], "g_wl", "g_wd"))
xr = x0 + NC * BW
xw = xr - (8 * (ww + HG) - HG)
y = snapy(yt + NB); yn = y; rows = []
for r in range(6):
    rows.append((y, "R0" if r % 2 == 0 else "MX"))
    y = snapy(y + wh + (HG if r % 2 == 0 else CH))
for n, _, _ in W:
    l, d = idx(n, "g_wl", "g_wd")
    c, r = l // 2, 3 * (l % 2) + d
    put(n, xw + c * (ww + HG), rows[r][0], rows[r][1])
top = snapy(y - CH + HG)
dw, dh = dim["qb_d_624x80m8"]
for j, (n, _, _) in enumerate(sorted(inst["qb_d_624x80m8"])):
    put(n, M + j * (dh + HG), yn, "R90")
assert M + len(inst["qb_d_624x80m8"]) * (dh + HG) <= xw - HG
top = max(top, snapy(yn + dw + HG))
dieW, dieH = hW + HUBX, round(top + M, 1)
assert xr <= dieW, (xr, dieW)
assert len(place) == sum(len(v) for v in inst.values())
A = dieW * dieH / 1e6
with open(outp, "w") as f:
    f.write("# generated by impl/r14/fp14.py\n")
    f.write("set P(DIE_AREA) {0 0 %.1f %.1f}\nset P(CORE_AREA) {0 0 %.1f %.1f}\n" % (dieW, dieH, dieW, dieH))
    f.write("set P(MACRO_PLACE) {\n" + "".join("  {%s %.3f %.3f %s}\n" % ((p[0].replace("\\", "\\\\"),) + p[1:]) for p in place) + "}\n")
    f.write("set ::QB11_IOY {%.1f %.1f}\nset ::QB11_YH %.3f\nset ::QB11_YT %.3f\nset ::QB11_ACT {%.3f %.3f %.3f %.3f}\n"
            % (yh + 20, ya - 20, yh, yt, xa, ya, x0, yt))
    f.write("set ::QB14_X0 %.3f\nset ::QB14_DIE {%.1f %.1f}\nset ::QB14_YN %.3f\n" % (x0, dieW, dieH, yn))
print("FP14 die %.1f x %.1f um = %.3f mm2 (f_tt needed 20.5 x A = %.0f MHz); hub %.0f x %.1f, array x %.0f..%.0f y %.1f..%.1f, "
      "act %.0f x %.0f at (%.1f, %.1f), gap %.0f x %.1f = %.3f mm2, weights from y %.1f, top %.1f"
      % (dieW, dieH, A, 20.5 * A, hW, yh, x0, xr, yh, yt, aW, aH, xa, ya, x0, ya - yh, x0 * (ya - yh) / 1e6, yn, top))

#!/usr/bin/env python3
"""R9b: hub pin plan (PIN_TCL data) from the boundary table and the column block LEF.
    python3 -I pins9.py <bnd_bits.txt> <qb_col_blk.lef> <x0 array west edge> <out pins9_data.tcl>
  column south pins: hub pin straight below, same layer / width / x (chip x = x0 + 390 c + x_col), on the north edge
  column north pins (t2, ctl, rst_n): north edge under column c (place_pins region, M8 allowed: they continue over the
      array in the top level)
  all other ports (act supply, sequencer / glue, host, chip IO, clk, rst_n): north edge x 12 .. x0 - 12 (west strip,
      where the act-supply block abuts)"""
import re
import sys
from collections import defaultdict

bits, lef, x0, out = sys.argv[1], sys.argv[2], float(sys.argv[3]), sys.argv[4]
t = open(lef).read()
W, H = map(float, re.search(r"SIZE\s+([\d.]+)\s+BY\s+([\d.]+)", t).groups())
geo = {}
for m in re.finditer(r"\n  PIN (\S+)(.*?)\n  END ", t, re.S):
    r = re.search(r"LAYER (\S+) ;\s*RECT\s+([\d.\-]+)\s+([\d.\-]+)\s+([\d.\-]+)\s+([\d.\-]+)", m.group(2))
    if not r:
        continue
    ly, x1, y1, x2, y2 = r.group(1), *map(float, r.groups()[1:])
    e = min([("W", x1), ("E", W - x2), ("S", y1), ("N", H - y2)], key=lambda z: z[1])[0]
    geo[m.group(1)] = (e, ly, x1, y1, x2, y2)
fixed, north, west, warn = [], defaultdict(list), [], 0
for ln in open(bits):
    f = ln.split()
    p, terms = f[0], (f[6] if len(f) > 6 else "")
    tl = [x for x in terms.split(";") if x]
    if not tl:
        west.append(p); continue
    cols = sorted({x.split(".")[0] for x in tl})
    if len(cols) > 1:
        warn += 1
    c, pin = tl[0].split(".", 1)
    c = int(c[3:])
    g = geo.get(pin) or (geo.get(pin[:-3]) if pin.endswith("[0]") else None)   # scalar column pins (p_ld, f_vld, ...)
    if g is None:
        west.append(p); warn += 1; continue
    e, ly, x1, y1, x2, y2 = g
    if e == "S":
        fixed.append((p, ly, round(x0 + 390.0 * c + (x1 + x2) / 2, 4), x2 - x1, y2 - y1))
    elif e == "N":
        north[c].append(p)
    else:
        west.append(p); warn += 1
br = lambda l: " ".join("{%s}" % x for x in l)
with open(out, "w") as fh:
    fh.write("# generated by impl/r9b/pins9.py: fixed column pins, north-of-array pins per column, west-strip pins\n")
    fh.write("set ::QB9_FIXED {\n" + "".join("  {{%s} %s %.4f %.4f %.4f}\n" % x for x in fixed) + "}\n")
    for c, l in sorted(north.items()):
        fh.write("set ::QB9_NORTH(%d) {%s}\n" % (c, br(l)))
    fh.write("set ::QB9_WEST {%s}\nset ::QB9_X0 %.1f\n" % (br(west), x0))
print("PINS9 fixed (column south) %d, column north %d, west strip %d, warnings %d" % (len(fixed), sum(len(v) for v in north.values()), len(west), warn))

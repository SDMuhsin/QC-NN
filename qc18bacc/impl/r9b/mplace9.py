#!/usr/bin/env python3
"""R9b hub floorplan = the south band of impl/r8/mplace.py (R6b/R8 chip floorplan) as a standalone block, chip x
coordinates (die x 0 .. 3990: west strip 0-860 + 8 columns from x0 = 860), hub die y 0 .. H (array bottom = H):
  params row (8, MX, right-aligned to the array east edge) at y M, B row (one per column, MX), 4 S rows (R0, pitch 392.4
  around the columns), channels CH [QB_CH 40]; logic band SB [QB_SB 300] between the last S row and the north edge.
  SW corner: FC (R90) at x M, IMG x 4 stacked (MX) east of it, params 9 (R0) above FC (north-west corner).
    python3 -I mplace9.py <macros.txt> <out.tcl>
<out.tcl>: P(DIE_AREA), P(CORE_AREA), P(MACRO_PLACE), ::QB9_H, ::QB9_X0 (array west edge)."""
import os
import re
import sys
E = lambda k, d: float(os.environ.get(k, d))
M, WEST, CH, SB, HG = 10.0, 850.0, E('QB_CH', 40), E('QB_SB', 300), 10.0
BW, NC = 390.0, 8
ROWH, SITE, CY0 = 1.8, 0.2, 5.0
snapx = lambda v: round(round(v / SITE) * SITE, 3)
snapy = lambda v: round(CY0 + round((v - CY0) / ROWH + 0.4999) * ROWH, 3)
inst = {}
for ln in open(sys.argv[1]):
    n, m, w, h = ln.split(); inst.setdefault(m, []).append((n, float(w), float(h)))
idx = lambda n, *ks: tuple(int(re.search(k + r'_?(\d+)_', n).group(1)) for k in ks)
dim = {m: v[0][1:] for m, v in inst.items()}
place = []
put = lambda n, x, y, o: place.append((n, snapx(x), snapy(y), o))
x0 = M + WEST
xr = x0 + NC * BW
dieW = snapx(xr + M)
P = sorted(inst['qb_p_240x144m2'], key=lambda t: idx(t[0], 'g_pm'))
pw, ph = dim['qb_p_240x144m2']
xs = xr - (8 * (pw + HG) - HG)
y = M
for k, (n, _, _) in enumerate(P[:8]): put(n, xs + k * (pw + HG), y, 'MX')
y = snapy(y + ph + CH)
ysw = y
Bm = sorted(inst['qb_b_128x128m1'], key=lambda t: idx(t[0], 'g_map', 'g_mm'))
bw, bh = dim['qb_b_128x128m1']
for c, (n, _, _) in enumerate(Bm): put(n, x0 + c * BW + (BW - bw) / 2, y, 'MX')
y = snapy(y + bh + CH)
S = sorted(inst['qb_s_256x128m1'], key=lambda t: idx(t[0], 'g_s'))
sw, sh = dim['qb_s_256x128m1']
for r in range(4):
    for c in range(8):
        put(S[8 * r + c][0], x0 + c * BW + (BW - sw) / 2 + (sw + HG - BW) * (c - 3.5), y, 'R0')
    y = snapy(y + sh + CH)
H = round(snapy(y - CH + SB) + 0.0, 3)
fw, fh = dim['qb_f_3232x128m8']
put(inst['qb_f_3232x128m8'][0][0], M, ysw, 'R90')
I = sorted(inst['qb_i_128x128m1'], key=lambda t: idx(t[0], 'g_img'))
iw, ih = dim['qb_i_128x128m1']
xi = M + fh + 2 * HG
for k, (n, _, _) in enumerate(I): put(n, xi, ysw + k * (ih + HG), 'MX')
# params 9: R0 above FC (R90 left its VDD ring unconnected to the M4 macro straps:
# check_power_grid PSM-0069 on r9b_a)
yp9 = snapy(ysw + fw + HG)
put(P[8][0], M, yp9, 'R0')
assert yp9 + ph <= H - 5, ('params 9 above the die', yp9 + ph, H)
assert ysw + fw <= H - 5, ('FC above the die', ysw + fw, H)
assert len(place) == sum(len(v) for v in inst.values())
with open(sys.argv[2], 'w') as f:
    f.write('# generated by impl/r9b/mplace9.py (CH %g SB %g)\n' % (CH, SB))
    f.write('set P(DIE_AREA) {0 0 %.1f %.3f}\nset P(CORE_AREA) {5 5 %.1f %.3f}\n' % (dieW, H, dieW - 5, H - 5))
    f.write('set P(MACRO_PLACE) {\n' + ''.join('  {%s %.3f %.3f %s}\n' % ((p[0].replace('\\', '\\\\'),) + p[1:]) for p in place) + '}\n')
    f.write('set ::QB9_H %.3f\nset ::QB9_X0 %.1f\n' % (H, x0))
print('MPLACE9 hub die %.1f x %.3f um = %.3f mm2, %d macros, S top %.1f, band %.0f' % (dieW, H, dieW * H / 1e6, len(place), y - CH, SB))

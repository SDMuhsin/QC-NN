#!/usr/bin/env python3
"""R23 (results/r23.md): hub floorplan = impl/r22/mplace22.py (unchanged, same env) with the column order QB_CORD
(impl/r23/cord.py): the S macros of column c (lanes 8 r + c) and params c (g_pm_<c>, c < 8) take the x of the same
row's macro of the column whose slot c moves to (column c -> slot pos(c): x of the identity object of column pos(c)).
B (map) macros stay: they connect to no column pin (results/r23.md 1.1).  Identity order: output = mplace22's.
    python3 -I mplace23.py <macros.txt> <out.tcl>"""
import os, re, runpy, sys
here = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, here)
import cord
mac, out = sys.argv[1], sys.argv[2]
tmp = out + '.mplace22'
sys.argv = [os.path.join(here, '../r22/mplace22.py'), mac, tmp]
runpy.run_path(sys.argv[0], run_name='__main__')
t = open(tmp).read(); os.remove(tmp)
P = cord.pos()
pl = re.search(r'set P\(MACRO_PLACE\) \{\n(.*?)\n\}', t, re.S)
rows = [ln.strip()[1:-1].split() for ln in pl.group(1).split('\n')]
def colk(n):
    m = re.search(r'g_s_(\d+)__u_m', n)
    if m: return ('S', int(m.group(1)) // 8), int(m.group(1)) % 8
    m = re.search(r'g_pm_(\d+)_', n)
    if m and int(m.group(1)) < 8: return ('P', 0), int(m.group(1))
    return None, None
ref = {}
for r in rows:
    g, c = colk(r[0])
    if g: ref[(g, c)] = r[1]
n = 0
for r in rows:
    g, c = colk(r[0])
    if g and P[c] != c:
        r[1] = ref[(g, P[c])]; n += 1
body = ['  {%s}' % ' '.join(r) for r in rows]
t = t[:pl.start(1)] + '\n'.join(body) + t[pl.end(1):]
t = t.replace('# generated by', '# impl/r23/mplace23.py QB_CORD %s; generated by' % ''.join(map(str, cord.order())), 1)
open(out, 'w').write(t)
print('MPLACE23 QB_CORD %s: %d S / params macros moved, written %s' % (''.join(map(str, cord.order())), n, out))

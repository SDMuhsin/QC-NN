#!/usr/bin/env python3
"""R23 (results/r23.md): hub pin plan = impl/r9b/pins9.py (unchanged, same arguments) with the column order QB_CORD
(impl/r23/cord.py): the fixed column-south pins of column c shift by 390 (pos(c) - c); the column-north pin list of
column c goes under slot pos(c) (pins9.tcl places ::QB9_NORTH(k) under slot k).  West-strip pins are unchanged.
    python3 -I pins23.py <bnd_bits.txt> <qb_col_blk.lef> <x0> <out pins9_data.tcl>"""
import os, re, runpy, sys
here = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, here)
import cord
out, x0 = sys.argv[4], float(sys.argv[3])
tmp = out + '.pins9'
sys.argv = [os.path.join(here, '../r9b/pins9.py')] + sys.argv[1:4] + [tmp]
runpy.run_path(sys.argv[0], run_name='__main__')
t = open(tmp).read(); os.remove(tmp)
P = cord.pos()
fx = re.search(r'set ::QB9_FIXED \{\n(.*?)\n\}\n', t, re.S)
lines, nf = [], 0
for ln in fx.group(1).split('\n'):
    m = re.match(r'(\s*\{\{.*?\} \S+ )([\d.]+)( .*)$', ln)
    if m:
        x = float(m.group(2)); c = int((x - x0) // 390.0)
        assert 0 <= c < 8, ln
        if P[c] != c: nf += 1
        ln = '%s%.4f%s' % (m.group(1), x + 390.0 * (P[c] - c), m.group(3))
    lines.append(ln)
t = t[:fx.start(1)] + '\n'.join(lines) + t[fx.end(1):]
t = re.sub(r'set ::QB9_NORTH\((\d)\)', lambda m: 'set ::QB9_NORTH(%d)' % P[int(m.group(1))], t)
t = t.replace('# generated by', '# impl/r23/pins23.py QB_CORD %s; generated by' % ''.join(map(str, cord.order())), 1)
open(out, 'w').write(t)
print('PINS23 QB_CORD %s: %d fixed column pins moved' % (''.join(map(str, cord.order())), nf))

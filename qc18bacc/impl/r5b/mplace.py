#!/usr/bin/env python3
"""R5b chip floorplan (results/r5b.md): <run>/macros.txt (name master w h, from dump_macros.tcl) -> mplace.tcl with
P(DIE_AREA), P(CORE_AREA), P(MACRO_PLACE).  Geometry (um, lower-left origin; env overrides in brackets):
  array    8 x qb_col_blk (390 x 3110) abutted, columns in index order west -> east, x0 = M + WEST [QB_WEST 900]
  south    (bottom -> top) params row (8, MX: pins up), B-map row (8, MX, one per column), 4 S rows (8 each, R0: rf_2p
           pins on both long edges), channels CH [QB_CH 40] where pins face; west of the B / S rows: image x4, params 9;
           then the south logic band SB [QB_SB 400] under the array
  north    logic band NB [QB_NB 200], 6 weight rows of 8 (R0 pins down / MX pins up pairs around CH channels; the 6
           macros of lanes 2c, 2c+1 in slot c, above column c's half of the row)
  west     strip WEST wide next to the array: FC (R90, pins east) and the two descriptor macros (R90) at its north end;
           the act-supply / sequencer / head logic fills the rest
usage: mplace.py <macros.txt> <out.tcl>"""
import os, re, sys
E = lambda k, d: float(os.environ.get(k, d))
M, WEST, CH, SB, NB, HG = 10.0, E('QB_WEST', 900), E('QB_CH', 40), E('QB_SB', 400), E('QB_NB', 200), 10.0
BW, BH, NC = 390.0, 3110.0, 8
ROWH, SITE, CY0 = 1.8, 0.2, 5.0
snapx = lambda v: round(round(v / SITE) * SITE, 3)
snapy = lambda v: round(CY0 + round((v - CY0) / ROWH + 0.4999) * ROWH, 3)
inst = {}
for ln in open(sys.argv[1]):
    n, m, w, h = ln.split(); inst.setdefault(m, []).append((n, float(w), float(h)))
def idx(n, *keys):
    return tuple(int(re.search(k + r'_?(\d+)_', n).group(1)) for k in keys)
dim = {m: v[0][1:] for m, v in inst.items()}
place = []
def put(n, x, y, o):
    place.append((n, snapx(x), snapy(y), o))
x0 = M + WEST
xr = x0 + NC * BW
ww, wh = dim['qb_w_204x144m2']
dieW = round(max(xr + M, 8 * (ww + HG) - HG + 2 * M + 20), 1)   # the weight / params rows are centred on the die
# ---- south
y = M
P = sorted(inst['qb_p_240x144m2'], key=lambda t: idx(t[0], 'g_pm'))
pw, ph = dim['qb_p_240x144m2']
xs = (dieW - (8 * (pw + HG) - HG)) / 2
for k, (n, _, _) in enumerate(P[:8]): put(n, xs + k * (pw + HG), y, 'MX')
y = snapy(y + ph + CH)
B = sorted(inst['qb_b_128x128m1'], key=lambda t: idx(t[0], 'g_map', 'g_mm'))
bw, bh = dim['qb_b_128x128m1']
for c, (n, _, _) in enumerate(B): put(n, x0 + c * BW + (BW - bw) / 2, y, 'MX')
I = sorted(inst['qb_i_128x128m1'], key=lambda t: idx(t[0], 'g_img'))
iw, ih = dim['qb_i_128x128m1']
west_slots = []                     # (y, height) of the south rows, for the west-side macros
west_slots.append(y)
y = snapy(y + bh + CH)
S = sorted(inst['qb_s_256x128m1'], key=lambda t: idx(t[0], 'g_s'))
sw, sh = dim['qb_s_256x128m1']
for r in range(4):
    for c in range(8):
        n = S[8 * r + c][0]
        put(n, x0 + c * BW + (BW - sw) / 2 + (sw + HG - BW) * (c - 3.5), y, 'R0')
    west_slots.append(y)
    y = snapy(y + sh + CH)
# west of the B / S rows: image x 4 (two per row), params 9
k = 0
for ys in west_slots[:2]:
    for j in range(2):
        put(I[k][0], M + j * (iw + HG), ys, 'MX'); k += 1
put(P[8][0], M, west_slots[2], 'MX')
ya = snapy(y - CH + SB)                 # array bottom
for c in range(NC):
    n = [t for t in inst['qb_col_blk'] if idx(t[0], 'g_c')[0] == c][0][0]
    put(n, x0 + c * BW, ya, 'R0')
yt = ya + BH
# ---- west strip north end: FC + descriptors (R90: pins east)
fw, fh = dim['qb_f_3232x128m8']
F = inst['qb_f_3232x128m8'][0][0]
put(F, M, yt - fw, 'R90')
dw, dh = dim['qb_d_624x80m8']
D = sorted(inst['qb_d_624x80m8'])
for j, (n, _, _) in enumerate(D): put(n, M + fh + HG, yt - (j + 1) * (dw + HG + 2) + HG, "R90")
assert M + fh + HG + dh <= x0 - 5, 'west strip too narrow for FC + descriptors'
# ---- north: weights, slot c = column c (lanes 2c, 2c+1), rows 0..5 = (lane parity, depth)
W = sorted(inst['qb_w_204x144m2'], key=lambda t: idx(t[0], 'g_wl', 'g_wd'))
xs = (dieW - (8 * (ww + HG) - HG)) / 2
y = snapy(yt + NB)
rows = []
for r in range(6):
    o = 'R0' if r % 2 == 0 else 'MX'
    rows.append((y, o))
    y = snapy(y + wh + (HG if r % 2 == 0 else CH))
for n, _, _ in W:
    l, d = idx(n, 'g_wl', 'g_wd')
    c, r = l // 2, 3 * (l % 2) + d
    put(n, xs + c * (ww + HG), rows[r][0], rows[r][1])
top = snapy(y)
dieW, dieH = snapx(dieW), round(top + M, 1)
n_all = sum(len(v) for v in inst.values())
assert len(place) == n_all, (len(place), n_all)
assert min(p[1] for p in place) >= M - 0.01
for n, x, yy, o in place:
    pass
with open(sys.argv[2], 'w') as f:
    f.write('# generated by impl/r5b/mplace.py (WEST %g CH %g SB %g NB %g)\n' % (WEST, CH, SB, NB))
    f.write('set P(DIE_AREA) {0 0 %.1f %.1f}\nset P(CORE_AREA) {5 5 %.1f %.1f}\n' % (dieW, dieH, dieW - 5, dieH - 5))
    f.write('set P(MACRO_PLACE) {\n' + ''.join('  {%s %.3f %.3f %s}\n' % ((p[0].replace('\\', '\\\\'),) + p[1:]) for p in place) + '}\n')
print('MPLACE die %.1f x %.1f um = %.3f mm2, %d instances, array at (%.1f, %.1f)' % (dieW, dieH, dieW * dieH / 1e6, len(place), x0, ya))

#!/usr/bin/env python3
"""R15 (results/r15.md): hub floorplan with the logic band moved between the S rows, same die as R12 b450.
Runs impl/r10b/mplace10.py unchanged (same env: QB_SB [450] fixes the die height H, QB_CH, QB_PGAP, QB_P8SLOT), then
moves S rows 2 and 3 north, keeping params / B / S rows 0-1 / west strip (FC, IMG, params 8) and the die as they are:
  QB15_FP base   mplace10 floorplan (band 450 above the 4 S rows = R12 b450)
  QB15_FP mid    one logic band between S rows 1 | 2: S row 3 top at the core top (H - 5 - QB15_NG [0])
  QB15_FP split  two half bands: S1 | S2 gap QB15_GAP [half] um, the rest above S row 3 (north edge)
  QB15_FP gap    S1 | S2 gap = QB15_GAP um (explicit), remainder above S row 3
S rows keep pitch sh + CH (S2 | S3 channel = CH).  Prints the y bands as 'MPLACE15 band <name> <y0> <y1>' and writes
::QB15_BANDS {name y0 y1 ...} (rows / bands for the analysis, lay15.py) into <out.tcl>.
    python3 -I mplace15.py <macros.txt> <out.tcl>"""
import os
import re
import runpy
import sys

here = os.path.dirname(os.path.abspath(__file__))
mac, out = sys.argv[1], sys.argv[2]
tmp = out + '.mplace10'
sys.argv = [os.path.join(here, '../r10b/mplace10.py'), mac, tmp]
g = runpy.run_path(sys.argv[0], run_name='__main__')     # base floorplan (prints MPLACE10 / MPLACE9 lines)
snapy, CH, H = g['snapy'], g['CH'], g['H']
sw, sh = g['dim']['qb_s_256x128m1']
t = open(tmp).read()
pl = re.search(r'set P\(MACRO_PLACE\) \{\n(.*?)\n\}', t, re.S)
rows = [ln.strip()[1:-1].split() for ln in pl.group(1).split('\n')]
srow = lambda n: (lambda m: int(m.group(1)) // 8 if m else None)(re.search(r'g_s_(\d+)__u_m', n))
ys = sorted({float(r[2]) for r in rows if srow(r[0]) is not None})
assert len(ys) == 4, ys
s1top = ys[1] + sh
ctop = H - 5.0 - float(os.environ.get('QB15_NG', 0))
fp = os.environ.get('QB15_FP', 'base')
gmax = ctop - (2 * sh + CH) - s1top                    # largest S1 | S2 gap with S row 3 under the core top
if fp == 'base':
    y2 = ys[2]
elif fp == 'mid':
    y2 = s1top + gmax
elif fp in ('split', 'gap'):
    gap = float(os.environ.get('QB15_GAP', (gmax + CH) / 2 if fp == 'split' else 0))
    y2 = s1top + gap
else:
    sys.exit('QB15_FP %s' % fp)
# snap down to a row (snapy rounds up)
y2 = snapy(y2) if snapy(y2) + 2 * sh + CH <= ctop + 1e-6 else round(snapy(y2) - 1.8, 3)
y3 = snapy(y2 + sh + CH)
if y3 + sh > ctop + 1e-6: y3 = round(y3 - 1.8, 3)
assert y3 + sh <= H - 5.0 + 1e-6 and y2 >= s1top, (y2, y3, s1top, H)
newy = {0: ys[0], 1: ys[1], 2: y2, 3: y3}
body = []
for r in rows:
    k = srow(r[0])
    if k is not None:
        r = [r[0], r[1], '%.3f' % newy[k], r[3]]
    body.append('  {%s}' % ' '.join(r))
t = t[:pl.start(1)] + '\n'.join(body) + t[pl.end(1):]
bands = [('S0', ys[0], ys[0] + sh), ('S1', ys[1], ys[1] + sh), ('S2', y2, y2 + sh), ('S3', y3, y3 + sh)]
lb = [('band_mid', s1top, y2)] if y2 - s1top > CH + 1 else []
if H - 5 - (y3 + sh) > CH + 1: lb.append(('band_top', y3 + sh, H))
bands += lb
t = t.replace('# generated by impl/r9b/mplace9.py', '# generated by impl/r15/mplace15.py (QB15_FP %s) from impl/r9b/mplace9.py' % fp)
t += 'set ::QB15_BANDS {%s}\n' % ' '.join('%s %.1f %.1f' % b for b in bands)
open(out, 'w').write(t)
os.remove(tmp)
for b in bands: print('MPLACE15 band %s %.1f %.1f (%.1f um)' % (b + (b[2] - b[1],)))
print('MPLACE15 %s die %.1f x %.3f um = %.3f mm2, S rows y %s, logic band(s) %s um' % (
    fp, g['dieW'], H, g['dieW'] * H / 1e6, ' '.join('%.1f' % newy[k] for k in range(4)),
    ' + '.join('%.0f' % (b[2] - b[1]) for b in lb)))

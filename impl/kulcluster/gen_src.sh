#!/usr/bin/env bash
# Synthesis sources of the KUL cluster on TSMC 65 nm, run on the build host from the repo root of the work tree:
#   impl/kulcluster/gen_src.sh <out_dir>    -> <out_dir>/{kul_tech.sv, kulcluster_syn_tech.sv, kul.f}
# 1. kulcluster_syn_tech.sv: the synthesis pickle of hw/kulcluster (hw/kulcluster/flist.sh kul-only, i.e.
#    generated/kulcluster_syn.sv; top KULCluster_snax_KUL_cluster_wrapper) without its generic
#    KULCluster_tc_sram and KULCluster_tc_clk_* modules (KULCluster_tc_sram_impl stays: it wraps tc_sram).
# 2. kul_tech.sv: the shared TSMC 65 nm overlay (hw/tech/tsmc65/tc_clk.sv: all clock cells; tc_sram.sv: the
#    tc_sram_qc_hold / tc_sram_qc_ff helpers) with every module name prefixed KULCluster_, unchanged otherwise.
#    The KUL-specific tc_sram (other macro shapes) is impl/kulcluster/tech/kul_tc_sram.sv.
# 3. kul.f: kul_tech.sv, tech/kul_tc_sram.sv, kulcluster_syn_tech.sv (absolute paths).
set -eu
HERE=$(cd "$(dirname "$0")" && pwd)
ROOT=$(cd "$HERE/../.." && pwd)
OUT=${1:?usage: gen_src.sh <out_dir>}
mkdir -p "$OUT"; OUT=$(cd "$OUT" && pwd)
PICKLE=$ROOT/hw/kulcluster/generated/kulcluster_syn.sv
TECH=$ROOT/hw/tech/tsmc65
[ -f "$PICKLE" ] || { echo "missing $PICKLE (hw/kulcluster/gen.sh)"; exit 1; }

# 1. strip the generic tech cells
awk 'BEGIN { skip = 0 }
     /^module KULCluster_tc_(sram|clk_[a-z0-9_]+)[ #(]/ && $2 != "KULCluster_tc_sram_impl" { skip = 1; n++ }
     !skip { print }
     skip && /^endmodule/ { skip = 0 }
     END { print "// gen_src.sh: removed " n " generic tech-cell modules" > "/dev/stderr" }' \
    "$PICKLE" > "$OUT/kulcluster_syn_tech.sv"

# 2. prefixed copies of the shared overlay (clock cells; tc_sram helpers without tc_sram itself)
{
  echo "// Generated by impl/kulcluster/gen_src.sh: hw/tech/tsmc65/{tc_clk,tc_sram}.sv with module names prefixed KULCluster_."
  sed -E 's/^module (tc_clk_[a-z0-9_]+)/module KULCluster_\1/' "$TECH/tc_clk.sv"
  awk '/^module tc_sram_qc_(hold|ff)/ { p = 1 } p { print } p && /^endmodule/ { p = 0 }' "$TECH/tc_sram.sv" |
      sed -E 's/^module (tc_sram_qc_[a-z]+)/module KULCluster_\1/'
} > "$OUT/kul_tech.sv"

n_rm=$(grep -cE '^module KULCluster_tc_(sram|clk_)' "$OUT/kulcluster_syn_tech.sv" || true)
n_tc=$(grep -c '^module KULCluster_' "$OUT/kul_tech.sv")
printf '%s\n' "$OUT/kul_tech.sv" "$HERE/tech/kul_tc_sram.sv" "$OUT/kulcluster_syn_tech.sv" > "$OUT/kul.f"
echo "GEN_SRC pickle modules left: $(grep -c '^module' "$OUT/kulcluster_syn_tech.sv") (tc_* left: $n_rm, expect 1 = tc_sram_impl), overlay modules: $n_tc"

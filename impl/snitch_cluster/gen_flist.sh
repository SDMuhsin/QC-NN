#!/usr/bin/env bash
# Regenerate the synthesis file list of one cluster variant from bender, run locally:
#   impl/snitch_cluster/gen_flist.sh fp        -> flist/fp.f        (primary DUT)
#   impl/snitch_cluster/gen_flist.sh chimera   -> flist/chimera.f   (chimera-exact, integer-only)
#
# fp      : the cluster the NN workloads run on (sim/cfg/chimera_fp.hjson: chimera's cluster with the upstream FP
#           compute cores).  Same RTL as sim/: the snitch_cluster workspace that sim/setup.sh stages
#           (build/sim/ws/chimera_fp, snitch_cluster c12ce9b with its own Bender.lock) and the clustergen wrapper
#           sim/build_hw.sh generates there.  The wrapper is copied to flist/fp/snitch_cluster_wrapper.sv (with its
#           config hash) so that the list does not depend on the sim build area.  Targets: rtl, snitch_cluster,
#           synthesis, asic.  Top: snitch_cluster_wrapper.
# chimera : chimera's own cluster as instantiated (hw/chimera_cluster.sv, no FPU / SSR / FREP), from
#           third_party/chimera with the targets of chimera's bender.mk (COMMON_TARGS) plus synthesis / asic.
#           Top: rtl/qc_snitch_cluster_top.sv.  chimera_cluster.sv is replaced by flist/chimera_cluster_dc.sv, a
#           sed copy that only adds .NumSsrsMax(1), .NumSsrs('{default: 1}) to its snitch_cluster instance: chimera
#           leaves both at 0 and snitch_cluster then slices SsrCfgs[i][NumSsrs[i]-1:0] with an unsigned -1, which DC
#           rejects (ELAB-210).  With Xssr = 0 and no FPU no SSR hardware is built for either value.
# Both: the asic target drops the generic tc_sram / tc_clk models (hw/tech/tsmc65/tsmc65.f replaces them).
# Dropped: the snitch_cluster target's generated wrapper (chimera: a testbench config, not used; fp: replaced by
# the copy) and axi_intf.sv (SV interfaces, unused by the cluster; DC keeps interface names in one global name
# space, where AXI_LITE clashes with idma_pkg's protocol enum literal AXI_LITE, VER-294).  idma_pkg.sv is moved
# to just after axi_pkg.sv (same clash; it needs only axi_pkg).  Paths are written relative to $QC_ROOT (repo root,
# set by the flow) so that the list works in any tree that mirrors the sources (sync_src.sh).
set -eu
HERE=$(cd "$(dirname "$0")" && pwd)
REPO=$(cd "$HERE/../.." && pwd)
BENDER=${BENDER:-$REPO/tools/bender/bin/bender}
VARIANT=${1:?usage: gen_flist.sh fp|chimera}
EXCLUDE='/target/snitch_cluster/generated/snitch_cluster_wrapper\.sv$|/axi-[0-9a-f]*/src/axi_intf\.sv$'
mkdir -p "$HERE/flist"
case "$VARIANT" in
fp)
    SRC=${QC_SIM_WS:-$REPO/build/sim/ws/chimera_fp}
    TARGETS="-t rtl -t snitch_cluster -t synthesis -t asic"
    W=$SRC/target/snitch_cluster/generated/snitch_cluster_wrapper.sv
    CFG=$REPO/sim/cfg/chimera_fp.hjson
    [ -f "$W" ] || { echo "missing $W (sim/setup.sh; sim/build_hw.sh generates it)"; exit 1; }
    mkdir -p "$HERE/flist/fp"
    { echo "// Copy of $(realpath --relative-to="$REPO" "$W")"
      echo "// (clustergen, sim/cfg/chimera_fp.hjson sha256 $(sha256sum "$CFG" | cut -c1-16)), by impl/snitch_cluster/gen_flist.sh."
      cat "$W"; } > "$HERE/flist/fp/snitch_cluster_wrapper.sv"
    TAIL="\$QC_ROOT/impl/snitch_cluster/flist/fp/snitch_cluster_wrapper.sv"
    ;;
chimera)
    SRC=$REPO/third_party/chimera
    TARGETS="-t synthesis -t asic -t snitch_cluster -t cv32a6_convolve -t cva6 -t rtl"
    P=$HERE/flist/chimera_cluster_dc.sv
    { echo "// Generated by impl/snitch_cluster/gen_flist.sh from third_party/chimera/hw/chimera_cluster.sv; see there."
      sed "s#^\(\s*\)\.Xdma\( *\)(\(.*\)),\$#&\n\1.NumSsrsMax(1),  // QC-NN: DC elaboration, see gen_flist.sh\n\1.NumSsrs   ('{default: 1}),#" \
          "$SRC/hw/chimera_cluster.sv"; } > "$P"
    [ "$(grep -c 'QC-NN' "$P")" = 1 ] || { echo "patch of chimera_cluster.sv did not apply"; exit 1; }
    TAIL=""
    ;;
*)  echo "unknown variant $VARIANT (fp | chimera)"; exit 1 ;;
esac
# shellcheck disable=SC2086
raw=$(cd "$SRC" && "$BENDER" script flist-plus $TARGETS)
idma_pkg=$(printf '%s\n' "$raw" | grep '/idma-[^/]*/src/idma_pkg\.sv$' | sed "s#$REPO/#\$QC_ROOT/#")
out=$HERE/flist/$VARIANT.f
{
    echo "// Generated by impl/snitch_cluster/gen_flist.sh $VARIANT (bender $("$BENDER" --version | awk '{print $2}'),"
    echo "// targets: $TARGETS).  Do not edit."
    printf '%s\n' "$raw" | grep -Ev "$EXCLUDE" | sed "s#$REPO/#\$QC_ROOT/#g" |
        awk -v P="$idma_pkg" '$0 == P { next } { print } /\/axi-[^\/]*\/src\/axi_pkg\.sv$/ { print P }' |
        sed "s#^\$QC_ROOT/third_party/chimera/hw/chimera_cluster\.sv\$#\$QC_ROOT/impl/snitch_cluster/flist/chimera_cluster_dc.sv#"
    if [ -n "$TAIL" ]; then echo "$TAIL"; fi
} > "$out"
echo "$out: $(grep -vc '^[+/]' "$out") files, $(grep -c '^+incdir' "$out") incdirs, $(grep -c '^+define' "$out") defines"
